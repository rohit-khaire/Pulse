import type { BuilderPlayer, Role, SquadsFile } from './types';
import {
  MODEL_ID,
  MODEL_LABEL,
  assignCredits,
  createHeuristicProvider,
  type ProjectionInput,
} from './projection';

/**
 * Builds squads.json from the Cricsheet `info.players` block of the featured match.
 *
 * What is REAL here: the 22 names, their teams, and the listed order (which in this
 * file follows the batting order).
 * What is an ASSUMPTION: the role label of each player (hand-labelled below, editable)
 * and the role-based overs. Nothing is taken from the match's actual scorecard.
 */

export const FEATURED_ROLES: Record<string, Role> = {
  // Rajasthan Royals
  'E Lewis': 'BAT',
  'YBK Jaiswal': 'BAT',
  'SV Samson': 'WK',
  'LS Livingstone': 'AR',
  'MK Lomror': 'AR',
  'R Parag': 'AR',
  'R Tewatia': 'AR',
  'CH Morris': 'AR',
  'C Sakariya': 'BOWL',
  'Kartik Tyagi': 'BOWL',
  'Mustafizur Rahman': 'BOWL',
  // Punjab Kings
  'KL Rahul': 'WK',
  'MA Agarwal': 'BAT',
  'AK Markram': 'BAT',
  'N Pooran': 'WK',
  'DJ Hooda': 'AR',
  'FA Allen': 'AR',
  'IC Porel': 'BOWL',
  'AU Rashid': 'BOWL',
  'Harpreet Brar': 'BOWL',
  'Arshdeep Singh': 'BOWL',
  'Mohammed Shami': 'BOWL',
};

export const TEAM_SHORT: Record<string, string> = {
  'Rajasthan Royals': 'RR',
  'Punjab Kings': 'PBKS',
};

/** Role-based overs: a rule, NOT the overs actually bowled in the match. */
export function defaultOvers(role: Role, battingPos: number): number {
  if (role === 'BOWL') return 4;
  if (role === 'AR') return battingPos <= 5 ? 2 : 3;
  return 0;
}

export interface MatchInfoLike {
  teams: string[];
  players: Record<string, string[]>;
}

export function buildSquadsFile(
  matchId: string,
  info: MatchInfoLike,
  roles: Record<string, Role> = FEATURED_ROLES
): SquadsFile {
  const rows: Omit<ProjectionInput, 'credits'>[] = [];
  const teamOf: Record<string, string> = {};

  for (const team of info.teams) {
    (info.players[team] || []).forEach((name, i) => {
      const role = roles[name];
      if (!role) throw new Error(`No role label for player "${name}"`);
      // Listed order = batting order for specialist batters. Bowlers are pinned to the tail
      // (9-11) so their projections do not differ just because of where they are listed.
      const battingPos = role === 'BOWL' ? Math.max(9, i + 1) : i + 1;
      rows.push({ name, role, battingPos, expectedOvers: defaultOvers(role, battingPos) });
      teamOf[name] = team;
    });
  }

  const credits = assignCredits(rows);
  const inputs: ProjectionInput[] = rows.map((r) => ({ ...r, credits: credits[r.name] }));
  const projections = createHeuristicProvider().projectAll(inputs);

  const players: BuilderPlayer[] = inputs.map((i) => ({
    name: i.name,
    team: teamOf[i.name],
    teamShort: TEAM_SHORT[teamOf[i.name]] ?? teamOf[i.name].slice(0, 3).toUpperCase(),
    role: i.role,
    credits: i.credits,
    battingPos: i.battingPos,
    expectedOvers: i.expectedOvers,
    projection: projections[i.name],
  }));

  return {
    _comment:
      'GENERATED by buildSquadsFile() (src/lib/builder/squadsBuilder.ts). Names/teams are real (Cricsheet 1254111); roles, credits and projections are ILLUSTRATIVE assumptions from projection.ts. Regenerate with: REGEN_SQUADS=1 pnpm test squads',
    matchId,
    matchLabel: `${info.teams[0]} vs ${info.teams[1]}`,
    modelId: MODEL_ID,
    modelLabel: MODEL_LABEL,
    disclaimer:
      'Illustrative model, not real form data. Roles, credits and projections are assumptions, not statistics.',
    players,
  };
}
